package com.tani.ocp.chapter1.flowcontrol;

public class IfElseExample {

    public static void main(String[] args) {
        // if-else controls program flow based on a condition.
        int score = 78;

        if (score >= 70) {
            System.out.println("Result: Pass");
        } else {
            System.out.println("Result: Review and retry");
        }
    }
}
